def clean_name(value: str) -> str:
    return ' '.join(re.sub(r'[^a-z0-9]+', ' ', value.casefold()).split())


ALIASES = {clean_name(alias): item for item in IDENTITIES for alias in item.aliases}

# Authoritative discovery data; frontend copy is generated by sync_ingredient_catalog.py.
# Search aliases are not blanket composition or substitution equivalences.
DISCOVERY = json.loads(Path(__file__).with_name('ingredient_discovery.json').read_text(encoding='utf-8'))
DISCOVERY_ALIASES = {clean_name(alias): item for item in DISCOVERY
                     for alias in [item['name'], item['canonical'], *item['aliases']]}
for item in DISCOVERY:
    if item['composition'] is None:
        continue  # Composite names are discoverable without asserting their composition.
    identity = next((x for x in IDENTITIES if x.name == item['canonical']), None)
    if identity is None and item['canonical'] not in ALIASES:
        identity = IngredientIdentity(item['canonical'], tuple(item['aliases']),
                                      item['composition'], tuple(item['allergens']))
        IDENTITIES.append(identity)
    if identity:
        for alias in item['aliases']:
            ALIASES.setdefault(clean_name(alias), identity)


def related_identity(left: str, right: str) -> bool:
    """Explicit direct parent/child relation means uncertain relevance, never HAVE."""
    a, b = DISCOVERY_ALIASES.get(left), DISCOVERY_ALIASES.get(right)
    return bool(a and b and (a['parent'] == b['canonical'] or b['parent'] == a['canonical']))


def search_ingredients(query: str, limit: int = 10) -> list[dict]:
    query = clean_name(query)
    if not query:
        return []
    def rank(item):
        names = [clean_name(item['name']), clean_name(item['canonical'])]
        aliases = [clean_name(x) for x in item['aliases']]
        checks = [query in names, query in aliases,
                  any(x.startswith(query) for x in names), any(x.startswith(query) for x in aliases),
                  any(query in x for x in names), any(query in x for x in aliases)]
        return next((i for i, match in enumerate(checks) if match), 6)
    return sorted((x for x in DISCOVERY if rank(x) < 6),
                  key=lambda x: (rank(x), clean_name(x['name']), x['id']))[:limit]


def identity_for(name: str) -> IngredientIdentity | None:
    return ALIASES.get(clean_name(name))
