"""Small identity vocabulary, not a nutrient database or product safety certificate.

Only exact whole-food aliases establish a composition category. Unknown composites,
brands, and qualifiers are intentionally unresolved. No numeric nutrition is stored here.
"""
from dataclasses import dataclass
import re
import json
from pathlib import Path


@dataclass(frozen=True)
class IngredientIdentity:
    name: str
    aliases: tuple[str, ...]
    category: str = 'plant'
    allergens: tuple[str, ...] = ()


